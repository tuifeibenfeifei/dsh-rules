/**
 * 把选中的层拼成一段 Markdown 规则文本。
 * @param {string[]} layerIds 要启用的层，如 ['core','behavior']
 * @param {object} [opts] { personalText }
 */
export function buildRuleText(layerIds, opts = {}) {
  const picked = LAYERS.filter((l) => layerIds.includes(l.id))
  const parts = []

  for (const layer of picked) {
    if (layer.id === 'personal') {
      const text = String(opts.personalText || '').trim()
      if (!text) continue
      parts.push('## 个人规则\n\n' + text)
      continue
    }
    for (const rule of layer.rules) {
      parts.push('## ' + rule.title + '\n' + rule.lines.join('\n'))
    }
  }

  return parts.join('\n\n')
}

/** 规则总条数，用于界面提示篇幅。 */
export function countRules(layerIds) {
  return LAYERS.filter((l) => layerIds.includes(l.id))
    .reduce((n, l) => n + l.rules.length, 0)
}

/**
 * 估算启用后的指令行数，用于提示是否接近上限。
 *
 * 为什么需要：实测前沿模型可靠遵循约 150–200 条指令，模型自身系统提示
 * 已占约 50 条。超过预算后遵守率下降，加规则反而变差。
 */
export function estimateLines(layerIds, opts = {}) {
  const text = buildRuleText(layerIds, opts)
  return text ? text.split('\n').length : 0
}

