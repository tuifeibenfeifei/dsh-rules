// 通用规则模板库。
//
// ## 设计依据
//
// 从多个成熟规则集归纳出来的硬约束（2026-11 调研）：
//
//  - 前沿模型只能可靠遵循约 150–200 条指令，模型自身系统提示已占约 50 条。
//    （khasky/awesome-agents-md 用 CI 卡这个预算；IFScale 的实测）
//  - 30 条以上警告型规则会出现「过度探索陷阱」，输出质量下降最多 30%。
//    （Augment Code）
//  - 主文件建议 100–150 行、32 KiB 以内。超了要么被截断，要么注意力稀释。
//    （Anthropic 官方指导 + Codex 的 project_doc_max_bytes）
//  - 规则越长，核心约束越容易被淹没；65 行的 Karpathy 版本跑赢 200 行的补丁集。
//  - GitHub 从 2500+ 仓库总结：具体胜于抽象；每条「不要」配一条「要」；
//    最差的规则是没有例子的抽象要求。
//
// 所以本模板的设计取舍：
//   ① 分层，默认只装 core，需要什么加什么，不一次性堆满
//   ② 每条都写成可判定的祈使句，并附「违反示例」
//   ③ 全部模板加起来约 200 条线，单层启用时远低于预算
//
// ## 各层
//
//   core      安全底线    装上就该有，不做会真出事
//   behavior  工程纪律    怎么动手、怎么收尾
//   quality   代码质量    写代码时的常规约束
//   safety    安全与隐私  密钥、注入、依赖、数据
//   collab    协作与版本  提交、评审、文档
//   personal  个人规则    留空，使用者自己填
//
// 每层都不含任何个人偏好，可跨机器、跨项目复用。

